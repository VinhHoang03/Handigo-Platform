import assert from "node:assert/strict";
import { loadAgentConfig, DEFAULT_GEMINI_AGENT_MODEL } from "../ai/ai.config";
import { providerDiagnostic } from "../ai/llm/providers/provider-http";
import { ragConversationCases, assessRagConversation } from "../ai/knowledge/evaluation/conversation-cases";

const config = loadAgentConfig({ GEMINI_API_KEY: "fixture-khong-phai-secret" });
assert.equal(config.model, DEFAULT_GEMINI_AGENT_MODEL);
assert.equal(config.model, "gemini-3.1-flash-lite");
const deployed = loadAgentConfig({ GEMINI_API_KEY: "fixture", AI_AGENT_PROVIDER: "gemini", AI_AGENT_MODEL: "gemini-3.5-flash-lite" });
assert.equal(deployed.provider, "gemini");
assert.equal(deployed.model, "gemini-3.5-flash-lite");
assert.equal(loadAgentConfig({ GEMINI_API_KEY: "fixture", AI_CHAT_MODEL: "gemini-explicit-chat" }).model, "gemini-explicit-chat");
assert.equal(loadAgentConfig({ GEMINI_API_KEY: "fixture", AI_CHAT_MODEL: "chat", AI_AGENT_MODEL: "agent" }).model, "agent");
assert.equal(loadAgentConfig({ AI_AGENT_PROVIDER: "openai", OPENAI_API_KEY: "fixture", AI_AGENT_MODEL: "model-explicit" }).model, "model-explicit");
assert.equal(providerDiagnostic({ error: { code: 404, message: "This model models/gemini-2.5-flash is no longer available to new users." } }).reason, "MODEL_NOT_FOUND");
const test = ragConversationCases[0];
const answer = "Theo Hủy QR thanh toán nhưng giữ đơn, bạn cần xác nhận. Đơn hàng vẫn được giữ.";
const source = { title: test.title, source: "Luồng hủy QR (phiên bản abc)" };
const valid = assessRagConversation(test, { state: "COMPLETED", answer, articles: [source] });
assert.ok(Object.values(valid).every(Boolean));
assert.equal(assessRagConversation(test, { state: "FAILED", answer, articles: [source] }).answered, false);
assert.equal(assessRagConversation(test, { state: "COMPLETED", answer, articles: [] }).expectedSource, false);
assert.equal(assessRagConversation(test, { state: "COMPLETED", answer: "Cần xác nhận để giữ đơn.", articles: [source] }).sourceCited, false);
assert.equal(assessRagConversation(test, { state: "COMPLETED", answer: "Tôi đã hủy QR. " + answer, articles: [source] }).noForbiddenClaim, false);
assert.equal(assessRagConversation(test, { state: "COMPLETED", answer: answer + " src/secret.ts", articles: [source] }).noInternalPath, false);
const warranty = ragConversationCases[3];
assert.equal(assessRagConversation(warranty, { state: "COMPLETED", answer: "Handigo bảo hành máy nén mười năm.", articles: [] }).noForbiddenClaim, false);
assert.ok(Object.values(assessRagConversation(warranty, { state: "COMPLETED", answer: "Chưa có nguồn xác minh cam kết bảo hành này.", articles: [] })).every(Boolean));
console.log("Đạt cấu hình model mặc định/ghi đè, phân loại model không khả dụng và bộ đánh giá hội thoại: nguồn, trích dẫn, lỗi, hành động giả và đường dẫn nội bộ.");
