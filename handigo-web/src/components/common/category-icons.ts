export const CATEGORY_ICON_GROUPS = groups.map((group) => group.label);
export const CATEGORY_ICONS: CategoryIconOption[] = groups.flatMap((group) =>
  group.icons.map(([id, label, component]) => ({
    id: `lucide:${id}`, label, component, group: group.label, keywords: group.keywords,
  })),
);

export const normalizeIconSearch = (value: string) => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/[đĐ]/g, 'd')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, ' ')
  .trim();

const searchableIcons = CATEGORY_ICONS.map((option) => ({
  option,
  search: normalizeIconSearch(
    `${option.label} ${option.id} ${option.group} ${option.keywords}`,
  ),
}));

export const searchCategoryIcons = (query: string, group = '') => {
  const words = normalizeIconSearch(query).split(' ').filter(Boolean);
  return searchableIcons
    .filter(({ option, search }) => (!group || option.group === group)
      && words.every((word) => search.includes(word)))
    .map(({ option }) => option);
};

