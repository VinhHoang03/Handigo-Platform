export const getAvailableCategoryIconColor = (usedColors: string[]) => {
  const used = new Set(usedColors.map((color) => color.toLowerCase()));
  const preset = CATEGORY_ICON_COLORS.find((color) => !used.has(color.value));
  if (preset) return preset.value;
  let value = 0x3525cd;
  while (used.has(`#${value.toString(16).padStart(6, '0')}`)) {
    value = (value + 0x9e3779) % 0x1000000;
  }
  return `#${value.toString(16).padStart(6, '0')}`;
};

export const isCategoryIconColor = (color?: string | null): color is string =>
  typeof color === 'string' && /^#[0-9a-f]{6}$/i.test(color);

