const iconsById = new Map(CATEGORY_ICONS.map((option) => [option.id, option]));

export const resolveCategoryIcon = (icon?: string | null, name?: string) => {
  for (const value of [icon, name]) {
    const exact = iconsById.get(value || '');
    if (exact) return exact;
    const key = normalizeIconSearch(value || '').replace(/ /g, '_');
    const option = iconsById.get(`lucide:${legacyAliases[key] || key}`);
    if (option) return option;
  }
  return iconsById.get('lucide:grid2_x2')!;
};

